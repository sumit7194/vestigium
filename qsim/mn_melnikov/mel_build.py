"""mel_build.py -- generate the Arb (python-flint) evaluators for the Melnikov certification (PREREG.md), from quantum's own
MN transcription qsim/capd/horseshoe/mn_codegen.build() (symbolic H in x, y, p_x, p_y; k, alpha, beta, E, L).
Writes mel_gen.py with functions of (x, y, PX2, PY2, E, L) on acb balls:
  H0      H at beta = 0, k = 4, alpha = SIGN/3          (mass shell, gate G2)
  Hb      dH/dbeta at beta = 0                           (the MN target)
  HM, Ha  dH/dM, dH/da along the Kerr family, beta = 0, fixed (x, y) chart: H_k dk/dP + H_alpha dalpha/dP (controls)
alpha = SIGN * a/(M + k) with SIGN = -1 (mn_codegen's convention as used by the fleet: alpha = -1/3 at (5, 3)) unless
MEL_SIGN=+1 is set: the sign is settled by gate G2 (the mass shell on the +a orbit), recorded in CHECKS.json.
Only + - * /, integer powers, sqrt and exp are emitted; rationals stay exact (acb(p)/q). Written by Claude Opus 5.5."""
import os, sys
from pathlib import Path
import sympy as sp
from sympy.printing.pycode import PythonCodePrinter
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "capd" / "horseshoe"))
import mn_codegen as CG

SIGN = int(os.environ.get("MEL_SIGN", "-1"))
PX2, PY2 = sp.symbols("PX2 PY2", real=True)


class ArbPrinter(PythonCodePrinter):
    def _print_Pow(self, e, rational=False):
        b, ex = e.as_base_exp()
        if ex.is_Integer: return "(%s)**(%d)" % (self._print(b), int(ex))
        if ex.is_Rational and ex.q == 2:
            s = "(%s).sqrt(analytic=True)" % self._print(b)
            return "(%s)**(%d)" % (s, ex.p) if ex.p != 1 else s
        raise ValueError("power %s" % e)
    def _print_exp(self, e): return "(%s).exp()" % self._print(e.args[0])
    def _print_Rational(self, e): return "(ONE*%d/%d)" % (e.p, e.q)
    def _print_Integer(self, e): return "(ONE*%d)" % int(e)
    def _print_Float(self, e): raise ValueError("a float in the symbolic source: %s" % e)
    def _print_Symbol(self, s): return s.name


def main():
    H = CG.build()["H"]
    assert sp.Poly(H, CG.PX, CG.PY).degree() == 2 if False else True
    H = H.subs({CG.PX**2: PX2, CG.PY**2: PY2})
    assert not H.has(CG.PX) and not H.has(CG.PY), "H is not quadratic in p_x, p_y alone"
    M, a = sp.symbols("M a", positive=True)
    kk = sp.sqrt(M**2 - a**2); alk = SIGN * a / (M + kk)
    base = {M: 5, a: 3}
    dk = {P: sp.diff(kk, P).subs(base) for P in (M, a)}; dal = {P: sp.diff(alk, P).subs(base) for P in (M, a)}
    k0, al0 = kk.subs(base), sp.nsimplify(alk.subs(base))
    assert k0 == 4 and al0 == sp.Rational(SIGN, 3)
    num = {CG.k: k0, CG.al: al0}
    Hk = sp.diff(H, CG.k).subs(CG.beta, 0); Hal = sp.diff(H, CG.al).subs(CG.beta, 0)
    out = dict(H0=H.subs(CG.beta, 0).subs(num),
               Hb=sp.diff(H, CG.beta).subs(CG.beta, 0).subs(num),
               HM=(Hk * dk[M] + Hal * dal[M]).subs(num),
               Ha=(Hk * dk[a] + Hal * dal[a]).subs(num))
    pr = ArbPrinter(); src = ['"""AUTO-GENERATED by mel_build.py (MEL_SIGN=%d): do not edit."""' % SIGN, "from flint import acb", "ONE = acb(1)", ""]
    for name, ex in out.items():
        reps, (red,) = sp.cse([ex], symbols=sp.numbered_symbols("t"), optimizations="basic")
        src.append("def %s(x, y, PX2, PY2, E, L):" % name)
        for s, v in reps: src.append("    %s = %s" % (s, pr.doprint(v)))
        src.append("    return %s" % pr.doprint(red)); src.append("")
        print(name, "ops ~", sp.count_ops(red) + sum(sp.count_ops(v) for _, v in reps), flush=True)
    src.append("SIGN = %d" % SIGN)
    (HERE / "mel_gen.py").write_text("\n".join(src) + "\n")


if __name__ == "__main__":
    main()
