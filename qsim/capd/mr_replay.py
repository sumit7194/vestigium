"""CAPD third replay of the Morales-Ramis certificates: generator + runner (ARB-FREE on the CAPD side).

Fields  -> C++ header (tests/gen/<tag>.h) for tests/replay_driver.cpp:
  * exact rational fields: p = Pp/Qp, q = Pq/Qq, polynomials in t and E_1..E_K, E_k = exp(w_k(t)), w_k = n_k/d_k;
  * coefficients are passed as exact dyadic enclosures (hex, computed here with Python integers -- no floating
    point, no Arb); the C++ side is CAPD MpInterval on MPFR only.
Loops   -> the certificate's own polylines (ia_hub.loop_points: the exact float vertices v1 and v2 transported).
Usage (dev):  mr_replay.py dev-mine <family> <row>    (fields from this repo's sympy code: ENGINEERING ONLY)
              mr_replay.py run <fields.json> <family> <row> [secondary]
"""
