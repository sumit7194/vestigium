"""Generate gen/mn_field.h: the B10-regularised MN/Kerr reduced field as C++ templates on a scalar type S (CAPD Node for
the integrator; MpInterval for the S4/S9 checks), from ONE symbolic source, after sympy CSE.

Symbols left symbolic (passed at run time as exact-rational interval enclosures c[]):
  c[0] = k, c[1] = alpha, c[2] = beta, c[3] = E, c[4] = L.
Generated functions:
  mn_field(in, out, c)   Hamilton's equations, in = (x, y, p_x, p_y)
  mn_H(in, c)            H_red = 1/2 (g^xx p_x^2 + g^yy p_y^2) + V
  mn_gpp(x, y, c)        regularised g_phiphi (B10)
  mn_B(x, y, c)          B (> 0 certifies det g < 0 together with x > 1, |y| < 1)
  mn_gyy(x, y, c), mn_gxx(x, y, c), mn_V(x, y, c)   for the p_y lift on the section
exp -> node_exp / interval exp, sqrt -> sqrt; rational powers are rewritten as products of sqrt and integer powers."""
import sys
from pathlib import Path
import sympy as sp
import mn_field_gate as Qg
from sympy.printing.cxx import CXX17CodePrinter

HERE = Path(__file__).resolve().parent
x, y, PX, PY = sp.symbols("x y p_x p_y", real=True)
k, al, beta, E, L = sp.symbols("k alpha beta E L", real=True)


def build():
    Rr = sp.sqrt(x**2 + y**2 - 1); u = x*y/Rr; P = [sp.legendre(l, u) for l in range(4)]
    psi = beta*P[2]/Rr**3
    aexp = -al*sp.exp(-2*beta*(-1 + sum((x - y)*P[l]/Rr**(l + 1) for l in range(3))))
    bexp = al*sp.exp(2*beta*(1 + sum((-1)**(3 - l)*(x + y)*P[l]/Rr**(l + 1) for l in range(3))))
    Gx = 3*beta**2*(P[3]**2 - P[2]**2)/Rr**6 + 2*beta*sum(((x - y) + (-1)**l*(x + y))*P[l]/Rr**(l + 1) - 2 for l in range(3)) + 8*beta
    sub = {Qg.x: x, Qg.y: y, Qg.a: aexp, Qg.b: bexp}
    A, B, C = (e.subs(sub) for e in (Qg.A, Qg.B, Qg.C))
    Qp, r = sp.div(sp.Poly(sp.expand((Qg.x**2 - 1)*(1 - Qg.y**2)*Qg.B**2 - 4*Qg.C**2), Qg.x, Qg.y, Qg.a, Qg.b),
                   sp.Poly(Qg.A, Qg.x, Qg.y, Qg.a, Qg.b))
    assert r.is_zero
    Qx = Qp.as_expr().subs(sub)
    w0 = 4*k*al/(1 - al**2); rho2 = k**2*(x**2 - 1)*(1 - y**2); E2 = sp.exp(2*psi)
    Lp = L + w0*E
    V = (E2*A*Lp**2 - 4*k*C*E*Lp - k**2*E**2*Qx/E2)/(2*rho2*B)
    gxx = E2*(x**2 - 1)*(1 - al**2)**2/(k**2*B*sp.exp(Gx))
    gyy = E2*(1 - y**2)*(1 - al**2)**2/(k**2*B*sp.exp(Gx))
    gpp = (k**2*Qx/E2 + 4*k*w0*C - E2*w0**2*A)/B
    H = (gxx*PX**2 + gyy*PY**2)/2 + V
    field = [sp.diff(H, PX), sp.diff(H, PY), -sp.diff(H, x), -sp.diff(H, y)]
    return dict(field=field, H=H, gpp=gpp, B=B, gxx=gxx, gyy=gyy, V=V)


class NodePrinter(CXX17CodePrinter):
    """prints only + - * /, exp, sqrt and integer powers (as repeated products); rationals become S(p)/S(q)"""
    def _print_Pow(self, e):
        b, ex = e.as_base_exp()
        if ex.is_Integer:
            n = int(ex)
            if n == 0: return "S(1)"
            body = "*".join(["(" + self._print(b) + ")"] * abs(n))
            return "(" + body + ")" if n > 0 else "(S(1)/(" + body + "))"   # parenthesised: a/b**3 must not become a/b*b*b
        if ex.is_Rational and ex.q == 2:                       # b^(p/2) = sqrt(b)^p
            return self._print(sp.Pow(sp.Function("SQRT")(b), ex.p, evaluate=False))
        raise ValueError("unsupported power " + str(e))
    def _print_Function(self, e):
        if e.func.__name__ == "SQRT": return "sqrt(" + self._print(e.args[0]) + ")"
        return super()._print_Function(e)
    def _print_exp(self, e): return "mn_exp(" + self._print(e.args[0]) + ")"
    def _print_Rational(self, e): return "(S(%d)/S(%d))" % (e.p, e.q)
    def _print_Integer(self, e): return "S(%d)" % int(e)
    def _print_Symbol(self, s):
        m = {"x": "in[0]", "y": "in[1]", "p_x": "in[2]", "p_y": "in[3]", "k": "c[0]", "alpha": "c[1]", "beta": "c[2]",
             "E": "c[3]", "L": "c[4]"}
        return m.get(s.name, s.name)


def emit(name, exprs, args="const S* in, S* out, const S* c"):
    reps, red = sp.cse(exprs, symbols=sp.numbered_symbols("t"), optimizations="basic")
    pr = NodePrinter()
    lines = [f"template <class S> inline void {name}({args}) {{"]
    for s_, e in reps:
        lines.append(f"  S {s_} = {pr.doprint(e)};")
    for i, e in enumerate(red):
        lines.append(f"  out[{i}] = {pr.doprint(e)};")
    lines.append("}")
    nops = sum(sp.count_ops(e) for _, e in reps) + sum(sp.count_ops(e) for e in red)
    return "\n".join(lines), len(reps), nops


def main():
    X = build()
    blocks, stats = [], {}
    for name, exprs in (("mn_field", X["field"]), ("mn_H", [X["H"]]), ("mn_gpp", [X["gpp"]]), ("mn_B", [X["B"]]),
                        ("mn_lift", [X["gxx"], X["gyy"], X["V"]])):
        code, ncse, nops = emit(name, exprs)
        blocks.append(code); stats[name] = dict(cse_temps=ncse, ops=int(nops))
        print(name, stats[name], flush=True)
    hdr = ("// GENERATED by mn_codegen.py from one symbolic source (B10-regularised MN/Kerr reduced field). Do not edit.\n"
           "// c[0]=k c[1]=alpha c[2]=beta c[3]=E c[4]=L ; in = (x, y, p_x, p_y). mn_exp must be provided by the includer.\n"
           "#pragma once\n\n" + "\n\n".join(blocks) + "\n")
    (HERE / "gen").mkdir(exist_ok=True)
    (HERE / "gen" / "mn_field.h").write_text(hdr)
    (HERE / "gen" / "mn_field_stats.txt").write_text(repr(stats) + "\n")
    print("wrote gen/mn_field.h", len(hdr), "bytes")


if __name__ == "__main__":
    main()
