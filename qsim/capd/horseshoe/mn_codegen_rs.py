"""Generate kerr_rs/src/mn_field.rs: the B10-regularised MN/Kerr reduced field (and the p_y lift functions) as generic
Rust over a scalar trait Sc (implemented for f64 and for 4-direction dual numbers), from the SAME symbolic source as
gen/mn_field.h (mn_codegen.build(), the same CSE). The expressions are the C++ printer's (+ - * /, sqrt, mn_exp,
integer powers as products, rationals as S(p)/S(q)), rewritten mechanically into Rust syntax:
  S(n) -> S::from_i(n);  sqrt(e) -> sqrt(e) and mn_exp(e) -> mn_exp(e) (generic free functions);  in[k] -> inp[k];
  "S t = e;" -> "let t: S = e;".
So the Rust and C++ fields are the same expression DAG, evaluated in the same order."""
import re, sys
from pathlib import Path
import sympy as sp
import mn_codegen as CG

HERE = Path(__file__).resolve().parent


def emit_rs(name, exprs, nin):
    reps, red = sp.cse(exprs, symbols=sp.numbered_symbols("t"), optimizations="basic")
    pr = CG.NodePrinter()
    def rs(e):
        s = pr.doprint(e)
        s = re.sub(r"\bS\((-?\d+)\)", r"S::from_i(\1)", s)
        s = re.sub(r"\bin\[", "inp[", s)
        return s
    lines = [f"#[allow(non_snake_case, unused_parens, clippy::all)]",
             f"pub fn {name}<S: Sc>(inp: &[S; {nin}], out: &mut [S; {len(red)}], c: &[S; 5]) {{"]
    lines += [f"    let {s_}: S = {rs(e)};" for s_, e in reps]
    lines += [f"    out[{i}] = {rs(e)};" for i, e in enumerate(red)]
    lines.append("}")
    return "\n".join(lines)


def main():
    X = CG.build()
    blocks = [emit_rs("mn_field", X["field"], 4), emit_rs("mn_lift", [X["gxx"], X["gyy"], X["V"]], 2)]
    hdr = ("// GENERATED by mn_codegen_rs.py from the same symbolic source as gen/mn_field.h. Do not edit.\n"
           "// mn_field: inp = (x, y, p_x, p_y); mn_lift: inp = (x, y) -> (g^xx, g^yy, V); c = (k, alpha, beta, E, L).\n"
           "use crate::scalar::{Sc, sqrt, mn_exp};\n\n" + "\n\n".join(blocks) + "\n")
    out = HERE / "kerr_rs" / "src" / "mn_field.rs"; out.parent.mkdir(parents=True, exist_ok=True); out.write_text(hdr)
    print("wrote", out, len(hdr), "bytes")


if __name__ == "__main__":
    main()
