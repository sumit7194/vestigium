"""DIAGNOSTIC STAGE (not registered; hs_cover does not use it): generate gen/mn_field8.h, the B10-regularised MN/Kerr
reduced field AUGMENTED with a, b, E2 = e^{2 psi}, eG = e^{G} as state variables, with the Bridge's structured Q
(verified exactly equal to the division Q) and v13's grouped A, B, C. One symbolic source, sympy CSE, C++ templates on S.

States in[0..7] = (x, y, p_x, p_y, a, b, E2, eG); parameters c[0..4] = (k, alpha, beta, E, L).
On the invariant manifold a = a(x, y), b = b(x, y), E2 = exp(2 psi(x, y)), eG = exp(G(x, y)) the first four components
equal the 4-D field of mn_codegen.py, and the last four are the derivatives of a(x, y), ... along it (chain rule):
  a_v = -2 beta a ea_v,  b_v = 2 beta b eb_v,  E2_v = 2 E2 psi_v,  eG_v = eG G_v        (v = x, y)
  xdot = H_px, ydot = H_py, pxdot = -D_x H, pydot = -D_y H,  adot = a_x xdot + a_y ydot, ...
with D_v F = F_v + F_a a_v + F_b b_v + F_E2 E2_v + F_eG eG_v (F as a function of all eight).
Generated functions:
  mn8_field(in, out, c)   the 8-D field
  mn8_aux(in, out, c)     (a, b, E2, eG) from (x, y) by the ORIGINAL formulas (initial lift, consistency checks)
Squares are printed as sqr(.) (tight for intervals containing 0); other integer powers as products."""
import sys
from pathlib import Path
import sympy as sp
import mn_field_gate as Qg
import mn_codegen as CG

HERE = Path(__file__).resolve().parent
x, y, PX, PY = CG.x, CG.y, CG.PX, CG.PY
k, al, beta, E, L = CG.k, CG.al, CG.beta, CG.E, CG.L
a, b, E2, eG = sp.symbols("a b E2 eG", real=True)
STATE = [x, y, PX, PY, a, b, E2, eG]


def pieces():
    R = sp.sqrt(x**2 + y**2 - 1); u = x*y/R; P = [sp.legendre(l, u) for l in range(4)]
    ea = -1 + sum((x - y)*P[l]/R**(l + 1) for l in range(3))
    eb = 1 + sum((-1)**(3 - l)*(x + y)*P[l]/R**(l + 1) for l in range(3))
    psi = beta*P[2]/R**3
    G = 3*beta**2*(P[3]**2 - P[2]**2)/R**6 + 2*beta*sum(((x - y) + (-1)**l*(x + y))*P[l]/R**(l + 1) - 2 for l in range(3)) + 8*beta
    sub = {Qg.x: x, Qg.y: y, Qg.a: a, Qg.b: b}
    A, B, C = (e.subs(sub) for e in (Qg.A, Qg.B, Qg.C))            # v13's grouped forms (not expanded)
    Xs = (x + 1)**2 + a*b*(x - 1)**2; Ys = a*(1 + y)**2 + b*(1 - y)**2
    Q = (1 - y**2)*Xs**2 - (x**2 - 1)*Ys**2 + 4*a*b*(x**2 - 1)*(1 - y**2)**2   # the Bridge's structured Q
    w0 = 4*k*al/(1 - al**2); rho2 = k**2*(x**2 - 1)*(1 - y**2); Lp = L + w0*E
    V = (E2*A*Lp**2 - 4*k*C*E*Lp - k**2*E**2*Q/E2)/(2*rho2*B)
    gxx = E2*(x**2 - 1)*(1 - al**2)**2/(k**2*B*eG)
    gyy = E2*(1 - y**2)*(1 - al**2)**2/(k**2*B*eG)
    H = (gxx*PX**2 + gyy*PY**2)/2 + V
    aux = [-al*sp.exp(-2*beta*ea), al*sp.exp(2*beta*eb), sp.exp(2*psi), sp.exp(G)]
    return dict(ea=ea, eb=eb, psi=psi, G=G, A=A, B=B, C=C, Q=Q, V=V, gxx=gxx, gyy=gyy, H=H, aux=aux)


def build8():
    p = pieces()
    rate = {v: {a: -2*beta*a*sp.diff(p["ea"], v), b: 2*beta*b*sp.diff(p["eb"], v),
                E2: 2*E2*sp.diff(p["psi"], v), eG: eG*sp.diff(p["G"], v)} for v in (x, y)}
    def D(F, v): return sp.diff(F, v) + sum(sp.diff(F, s)*rate[v][s] for s in (a, b, E2, eG))
    H = p["H"]
    xd, yd = sp.diff(H, PX), sp.diff(H, PY)
    field = [xd, yd, -D(H, x), -D(H, y)] + [rate[x][s]*xd + rate[y][s]*yd for s in (a, b, E2, eG)]
    return field, p


class Printer8(CG.NodePrinter):
    def _print_Pow(self, e):
        b_, ex = e.as_base_exp()
        if ex == 2: return "sqr(" + self._print(b_) + ")"
        if ex == -2: return "(S(1)/sqr(" + self._print(b_) + "))"
        return super()._print_Pow(e)
    def _print_Symbol(self, s):
        m = {"x": "in[0]", "y": "in[1]", "p_x": "in[2]", "p_y": "in[3]", "a": "in[4]", "b": "in[5]", "E2": "in[6]",
             "eG": "in[7]", "k": "c[0]", "alpha": "c[1]", "beta": "c[2]", "E": "c[3]", "L": "c[4]"}
        return m.get(s.name, s.name)


def emit(name, exprs):
    reps, red = sp.cse(exprs, symbols=sp.numbered_symbols("t"), optimizations="basic")
    pr = Printer8()
    lines = [f"template <class S> inline void {name}(const S* in, S* out, const S* c) {{"]
    lines += [f"  S {s_} = {pr.doprint(e)};" for s_, e in reps]
    lines += [f"  out[{i}] = {pr.doprint(e)};" for i, e in enumerate(red)]
    lines.append("}")
    nops = sum(sp.count_ops(e) for _, e in reps) + sum(sp.count_ops(e) for e in red)
    return "\n".join(lines), len(reps), int(nops)


def main():
    field, p = build8()
    blocks, stats = [], {}
    for name, ex in (("mn8_field", field), ("mn8_aux", p["aux"])):
        code, nc, no = emit(name, ex); blocks.append(code); stats[name] = dict(cse_temps=nc, ops=no)
        print(name, stats[name], flush=True)
    hdr = ("// GENERATED by mn_codegen8.py (DIAGNOSTIC stage, not registered). Do not edit.\n"
           "// in = (x, y, p_x, p_y, a, b, E2, eG); c = (k, alpha, beta, E, L). mn_exp and sqr must be provided by the includer.\n"
           "#pragma once\n\n" + "\n\n".join(blocks) + "\n")
    (HERE / "gen" / "mn_field8.h").write_text(hdr)
    (HERE / "gen" / "mn_field8_stats.txt").write_text(repr(stats) + "\n")
    print("wrote gen/mn_field8.h", len(hdr), "bytes")


if __name__ == "__main__":
    main()
