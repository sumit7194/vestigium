"""DIAGNOSTIC STAGE (SECOND_ORDER_STEP_DESIGN.md P1/P2; not registered): generate gen/mn_field48.h, the 48-state
second-order variational extension of the 8-D augmented field (mn_codegen8.build8), from the same symbolic source:
  states  z (8), X1, X2 (8 each), X11, X12, X22 (8 each)        -> in[0..47]
  zdot   = f(z)
  Xidot  = Df(z) . Xi                                           (i = 1, 2)
  Xijdot = Df(z) . Xij + D2f(z)[Xi, Xj]                        (ij = 11, 12, 22)
D f . v and D2f[u, v] are built symbolically as directional derivatives (sum_k df/dz_k v_k, and the derivative of
that along u), then CSE'd. Also generated: mn48_dirs(in, out, c) = (Df.v, D2f[u, v]) for the gate (in = z, u, v)."""
import sys, time
from pathlib import Path
import sympy as sp
import mn_codegen8 as C8

HERE = Path(__file__).resolve().parent
Z = C8.STATE


def directional(F, v):
    return [sum(sp.diff(Fi, Z[k]) * v[k] for k in range(8)) for Fi in F]


def build48():
    F, _ = C8.build8()
    X1, X2, X11, X12, X22 = (sp.symbols(f"{n}_0:8", real=True) for n in ("X1", "X2", "X11", "X12", "X22"))
    t0 = time.time()
    J1, J2 = directional(F, X1), directional(F, X2)               # Df.X1, Df.X2
    H11, H12, H22 = directional(J1, X1), directional(J2, X1), directional(J2, X2)   # D2f[X1,X1], [X1,X2], [X2,X2]
    JX11, JX12, JX22 = directional(F, X11), directional(F, X12), directional(F, X22)
    out = list(F) + J1 + J2 + [a + b for a, b in zip(JX11, H11)] + [a + b for a, b in zip(JX12, H12)] + [a + b for a, b in zip(JX22, H22)]
    print("symbolic build %.0fs" % (time.time() - t0), flush=True)
    syms = list(Z) + list(X1) + list(X2) + list(X11) + list(X12) + list(X22)
    U, V = sp.symbols("U_0:8", real=True), sp.symbols("V_0:8", real=True)
    JV = directional(F, V); DUV = directional(JV, U)
    return out, syms, (list(JV) + list(DUV), list(Z) + list(U) + list(V))


class Printer48(C8.Printer8):
    def __init__(self, names):
        super().__init__(); self.names = names
    def _print_Symbol(self, s):
        if s.name in self.names: return self.names[s.name]
        return super()._print_Symbol(s)


def emit(name, exprs, syms):
    names = {str(s): f"in[{i}]" for i, s in enumerate(syms)}
    t0 = time.time()
    reps, red = sp.cse(exprs, symbols=sp.numbered_symbols("t"), optimizations="basic")
    pr = Printer48(names)
    lines = [f"template <class S> inline void {name}(const S* in, S* out, const S* c) {{"]
    lines += [f"  S {s_} = {pr.doprint(e)};" for s_, e in reps]
    lines += [f"  out[{i}] = {pr.doprint(e)};" for i, e in enumerate(red)]
    lines.append("}")
    nops = sum(sp.count_ops(e) for _, e in reps) + sum(sp.count_ops(e) for e in red)
    print(name, "cse %.0fs, temps %d, ops %d" % (time.time() - t0, len(reps), nops), flush=True)
    return "\n".join(lines)


def main():
    out, syms, (dirs, dsyms) = build48()
    blocks = [emit("mn48_field", out, syms), emit("mn48_dirs", dirs, dsyms)]
    hdr = ("// GENERATED by mn_codegen48.py (DIAGNOSTIC stage, not registered). Do not edit.\n"
           "// mn48_field: in = (z[8], X1[8], X2[8], X11[8], X12[8], X22[8]); mn48_dirs: in = (z[8], U[8], V[8]) -> (Df.V, D2f[U,V]).\n"
           "// c = (k, alpha, beta, E, L). mn_exp and sqr must be provided by the includer.\n#pragma once\n\n" + "\n\n".join(blocks) + "\n")
    (HERE / "gen" / "mn_field48.h").write_text(hdr)
    print("wrote gen/mn_field48.h", len(hdr), "bytes")


if __name__ == "__main__":
    main()
