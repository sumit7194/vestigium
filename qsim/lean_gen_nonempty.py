"""Generate lean/ZiglinCert/ZiglinCert/Certs/NonEmpty.lean (Bridge Lean faithfulness read, 2026-11-23, item 2).

Why: CertConclusion BG BH is vacuously true for an EMPTY box, and `check` does not test lo <= hi. Instead of changing
the cited `check` (which would change its hash), this SEPARATE file proves, by `decide +kernel`, that every certificate
box is non-empty, i.e. lo <= hi on every real and imaginary entry. `MB.nonempty_sound` turns that into "there is a
matrix in the box", so CertConclusion is not vacuous for these boxes. A must-fire lemma shows that the test rejects a
box with lo > hi.

The certificate list is read from Certs/All.lean, keeping only the positive certificates (the kerrctl_* controls are
expected to FAIL `check`, so they carry no CertConclusion). The Controls boxes G and H are included.
"""
import os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lean", "ZiglinCert", "ZiglinCert")
ALL = os.path.join(ROOT, "Certs", "All.lean")
OUT = os.path.join(ROOT, "Certs", "NonEmpty.lean")


def certs():
    names = re.findall(r"^import ZiglinCert\.Certs\.(\S+)$", open(ALL).read(), re.M)
    return [n for n in names if n not in ("Controls",) and not n.startswith("kerrctl")]


HEAD = '''/- AUTO-GENERATED by qsim/lean_gen_nonempty.py. Do not edit.
   Non-emptiness of every certificate box (Bridge Lean faithfulness read, 2026-11-23, item 2). This is a separate
   file: `check`, `cert_sound` and the certificate files are unchanged. -/
import ZiglinCert.Certs.All

namespace NonEmpty

/-- lo <= hi -/
def qne (I : QI) : Bool := decide (I.lo ≤ I.hi)
def cne (B : CI) : Bool := qne B.re && qne B.im
def mne (B : MB) : Bool := cne (B 0 0) && cne (B 0 1) && cne (B 1 0) && cne (B 1 1)

theorem qne_sound {I : QI} (h : qne I = true) : I.mem ((I.lo : ℚ) : ℝ) := by
  unfold qne at h
  exact ⟨le_rfl, by exact_mod_cast (of_decide_eq_true h)⟩

theorem cne_sound {B : CI} (h : cne B = true) : B.mem ⟨((B.re.lo : ℚ) : ℝ), ((B.im.lo : ℚ) : ℝ)⟩ := by
  unfold cne at h
  rw [Bool.and_eq_true] at h
  exact ⟨qne_sound h.1, qne_sound h.2⟩

/-- what non-emptiness means: some matrix lies in the box, so `CertConclusion` is not vacuous for it -/
theorem mne_sound {B : MB} (h : mne B = true) : ∃ G : M2, B.mem G := by
  unfold mne at h
  simp only [Bool.and_eq_true] at h
  obtain ⟨⟨⟨h00, h01⟩, h10⟩, h11⟩ := h
  refine ⟨Matrix.of fun i j => ⟨(((B i j).re.lo : ℚ) : ℝ), (((B i j).im.lo : ℚ) : ℝ)⟩, ?_⟩
  intro i j
  fin_cases i <;> fin_cases j
  · exact cne_sound h00
  · exact cne_sound h01
  · exact cne_sound h10
  · exact cne_sound h11

/-- MUST-FIRE: a box with lo > hi in one entry is rejected -/
def emptyBox : MB := fun _ _ => ⟨⟨1, 0⟩, ⟨0, 0⟩⟩
theorem must_fire_empty : mne emptyBox = false := by decide +kernel

/-- and a point box is accepted (the test is not constantly false) -/
def pointBox : MB := fun _ _ => ⟨⟨0, 0⟩, ⟨0, 0⟩⟩
theorem must_pass_point : mne pointBox = true := by decide +kernel

theorem controls_G : mne Certs.Controls.G = true := by decide +kernel
theorem controls_H : mne Certs.Controls.H = true := by decide +kernel
'''


def gen():
    body = [HEAD]
    for n in certs():
        body.append(f"theorem {n}_G_nonempty : mne Certs.{n}_G = true := by decide +kernel")
        body.append(f"theorem {n}_H_nonempty : mne Certs.{n}_H = true := by decide +kernel")
    body.append("")
    body.append("/-- every certificate: some pair of matrices lies in its boxes, so its CertConclusion is not vacuous -/")
    body.append("#print axioms mne_sound")
    body.append("#print axioms must_fire_empty")
    body.append("")
    body.append("end NonEmpty")
    open(OUT, "w").write("\n".join(body) + "\n")
    return OUT, len(certs())


if __name__ == "__main__":
    print(gen())
